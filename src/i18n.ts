const dictionaries: Record<Lang, Record<MessageKey, string>> = { en, ru };

export type TFunction = (key: MessageKey, vars?: Record<string, string | number>) => string;

/** Returns a translator for the given language. Placeholders look like {name}. */
export function makeT(lang: Lang): TFunction {
  const dict = dictionaries[lang];
  return (key, vars) => {
    let text: string = dict[key] ?? en[key] ?? key;
    if (vars) {
      for (const [k, v] of Object.entries(vars)) {
        text = text.split(`{${k}}`).join(String(v));
      }
    }
    return text;
  };
}

